#!/usr/bin/env python3
"""Merge every days/day-NN-<lang>-vN/bench.md (hyperfine markdown export) into benchmarks.md.

Each solution directory gets its own `## day-NN-<lang>-vN` section, ordered by
(day, lang, version). Sections already in benchmarks.md are kept unless a fresh
bench.md exists for that solution or its directory is gone.
"""

from __future__ import annotations

import platform
import re
import subprocess
import sys
from collections.abc import Callable
from datetime import date
from pathlib import Path

# Import the sibling module even under `python -P` / PYTHONSAFEPATH.
sys.path.insert(0, str(Path(__file__).resolve().parent))
from resolve_day import DIR_RE, solution_key  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent

HEADING = "# Benchmarks"
INTRO = (
    "Sections are regenerated by `just bench <day>` / `just bench-all`; "
    "numbers from different machines are not comparable."
)
DROP_COLUMNS = {"change", "factor", "relative"}
# Any level-2 heading; only names matching DIR_RE are kept (see parse_sections).
SECTION_RE = re.compile(r"^## (\S+)[ \t]*$", re.MULTILINE)
SEPARATOR_CELL_RE = re.compile(r"^:?-+:?$")
CELL_SPLIT_RE = re.compile(r"(?<!\\)\|")


def _run(cmd: list[str]) -> str:
    return subprocess.run(cmd, cwd=ROOT, capture_output=True, text=True, check=True).stdout.strip()


def cpu_name() -> str:
    try:
        if platform.system() == "Darwin":
            name = _run(["sysctl", "-n", "machdep.cpu.brand_string"])
            if name:
                return name
        elif platform.system() == "Linux":
            for line in Path("/proc/cpuinfo").read_text().splitlines():
                if line.startswith("model name"):
                    return line.split(":", 1)[1].strip()
    except Exception:
        pass
    return platform.processor() or platform.machine() or "unknown CPU"


def os_name() -> str:
    system = platform.system() or "unknown OS"
    if system == "Darwin":
        system, version = "macOS", platform.mac_ver()[0]
    else:
        version = platform.release()
    parts = f"{system} {version}".strip()
    return f"{parts} ({platform.machine() or 'unknown'})"


def git_commit() -> str:
    try:
        commit = _run(["git", "rev-parse", "--short", "HEAD"])
        if not commit:
            return "commit unknown"
        try:
            dirty = bool(_run(["git", "status", "--porcelain", "--untracked-files=no"]))
        except Exception:
            dirty = False
        return f"commit {commit}" + (" (dirty)" if dirty else "")
    except Exception:
        return "commit unknown"


def metadata_line(benched: date) -> str:
    """Best-effort one-line description of when/where the numbers were produced."""
    try:
        return f"Benchmarked {benched.isoformat()} on {cpu_name()}, {os_name()}, {git_commit()}"
    except Exception:
        return f"Benchmarked {benched.isoformat()}"


def _split_row(line: str) -> list[str]:
    inner = line.strip()
    if inner.startswith("|"):
        inner = inner[1:]
    if inner.endswith("|") and not inner.endswith("\\|"):
        inner = inner[:-1]
    return [cell.strip() for cell in CELL_SPLIT_RE.split(inner)]


def clean_table(text: str) -> str:
    """Drop hyperfine's relative columns; return text verbatim if it is not a table."""
    lines = [line for line in text.strip().splitlines() if line.strip()]
    if len(lines) < 2 or not all(line.lstrip().startswith("|") for line in lines):
        return text.strip()
    header = _split_row(lines[0])
    separator = _split_row(lines[1])
    if len(separator) != len(header) or not all(SEPARATOR_CELL_RE.match(c) for c in separator):
        return text.strip()
    rows = [_split_row(line) for line in lines[2:]]
    if any(len(row) != len(header) for row in rows):
        return text.strip()
    keep = [i for i, h in enumerate(header) if h.strip("` *").lower() not in DROP_COLUMNS]
    if not keep:
        return text.strip()

    def emit(cells: list[str]) -> str:
        return "| " + " | ".join(cells[i] for i in keep) + " |"

    return "\n".join([emit(header), "|" + "|".join(separator[i] for i in keep) + "|"] + [emit(r) for r in rows])


def sorted_sections(sections: dict[str, str]) -> dict[str, str]:
    """Order sections by (day, lang, version)."""
    return {name: sections[name] for name in sorted(sections, key=solution_key)}


def parse_sections(text: str) -> dict[str, str]:
    """Split a benchmarks.md into {day-NN-<lang>-vN: body}, body excluding the heading.

    Sections under any other `## ` heading (e.g. an old `## day-02`) are dropped.
    """
    matches = list(SECTION_RE.finditer(text))
    sections: dict[str, str] = {}
    for i, m in enumerate(matches):
        if not DIR_RE.match(m.group(1)):
            continue
        end = matches[i + 1].start() if i + 1 < len(matches) else len(text)
        sections[m.group(1)] = text[m.end():end].strip()
    return sections


def build_section(bench_text: str, metadata: str) -> str:
    return f"{metadata}\n\n{clean_table(bench_text)}"


def merge_sections(
    existing: str,
    root: Path,
    metadata: Callable[[date], str],
    existing_mtime: float | None = None,
) -> dict[str, str]:
    """Merge existing benchmarks.md text with the bench.md files under root/days.

    A solution's section is replaced only when it has no section yet or its bench.md
    is newer than benchmarks.md (existing_mtime; None means every bench.md is newer).
    """
    sections = parse_sections(existing)
    days_dir = root / "days"
    present = {p.name for p in days_dir.glob("day-*") if p.is_dir() and DIR_RE.match(p.name)}
    sections = {name: body for name, body in sections.items() if name in present}
    for name in present:
        bench = days_dir / name / "bench.md"
        if not bench.is_file():
            continue
        mtime = bench.stat().st_mtime
        if name in sections and existing_mtime is not None and mtime <= existing_mtime:
            continue
        sections[name] = build_section(bench.read_text(), metadata(date.fromtimestamp(mtime)))
    return sorted_sections(sections)


def render(sections: dict[str, str]) -> str:
    body = "\n\n".join(f"## {name}\n\n{text}" for name, text in sorted_sections(sections).items())
    return f"{HEADING}\n\n{INTRO}\n\n{body}\n"


def collect(root: Path, metadata: Callable[[date], str]) -> str | None:
    """Return the new benchmarks.md content, or None if there are no sections."""
    out = root / "benchmarks.md"
    existing = out.read_text() if out.is_file() else ""
    mtime = out.stat().st_mtime if out.is_file() else None
    sections = merge_sections(existing, root, metadata, mtime)
    return render(sections) if sections else None


def main() -> None:
    content = collect(ROOT, metadata_line)
    if content is None:
        print(
            "no days/day-NN-<lang>-vN/bench.md files found — run `just bench <day>` first",
            file=sys.stderr,
        )
        sys.exit(1)
    out = ROOT / "benchmarks.md"
    out.write_text(content)
    count = len(parse_sections(content))
    print(f"wrote {out.name} ({count} solutions)")


if __name__ == "__main__":
    main()
